import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export interface InstalledModule {
  id: string;
  packageName: string;
  dir: string;
}

const HEADER = '// AUTO-GENERATED by `pnpm modules:sync` — do not edit by hand.';

/** Every workspace package under modules/ whose package.json has `"isbp": { "module": true }`. */
export function discoverModules(root: string): InstalledModule[] {
  const base = join(root, 'modules');
  if (!existsSync(base)) return [];
  return readdirSync(base, { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(base, d.name, 'package.json')))
    .map((d) => {
      const pkg = JSON.parse(readFileSync(join(base, d.name, 'package.json'), 'utf8')) as {
        name: string;
        isbp?: { module?: boolean; id?: string };
      };
      return pkg.isbp?.module
        ? { id: pkg.isbp.id ?? d.name, packageName: pkg.name, dir: join(base, d.name) }
        : null;
    })
    .filter((m): m is InstalledModule => m !== null)
    .sort((a, b) => a.id.localeCompare(b.id));
}

const ident = (id: string) => id.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());

export function renderApiRegistry(mods: InstalledModule[]): string {
  return `${HEADER}
// Lists every installed module's server entry. Core is always first.
import type { ServerModule } from '@isbp/sdk/server';
import { coreModule } from '../core';
${mods.map((m) => `import ${ident(m.id)} from '${m.packageName}/server';`).join('\n')}

export const installedModules: ServerModule[] = [coreModule${mods.map((m) => `, ${ident(m.id)}`).join('')}];
`;
}

export function renderWebRegistry(mods: InstalledModule[]): string {
  return `${HEADER}
// Client-side registry of every installed module's web entry (pages are lazy-loaded).
import type { WebModule } from '@isbp/sdk/web';
${mods.map((m) => `import ${ident(m.id)} from '${m.packageName}/web';`).join('\n')}

export const webModules: Record<string, WebModule> = {${mods.map((m) => `\n  '${m.id}': ${ident(m.id)},`).join('')}${mods.length ? '\n' : ''}};
`;
}

export function renderMessagesRegistry(mods: InstalledModule[]): string {
  const entries = mods.map(
    (m) => `  '${m.id}': {
    en: () => import('${m.packageName}/messages/en.json'),
    'zh-TW': () => import('${m.packageName}/messages/zh-TW.json'),
    'ja-JP': () => import('${m.packageName}/messages/ja-JP.json'),
  },`,
  );
  return `${HEADER}
// Server-side loaders for every installed module's message catalogs (namespace = module id).
import type { Locale, Messages } from '@isbp/i18n';

type Loader = () => Promise<{ default: Messages }>;

export const moduleMessages: Record<string, Record<Locale, Loader>> = {${entries.length ? `\n${entries.join('\n')}\n` : ''}};
`;
}

/** Ensures `apps/{api,web}` depend on every installed module (workspace protocol). */
export function syncAppDependencies(root: string, mods: InstalledModule[], write: boolean): string[] {
  const changed: string[] = [];
  for (const app of ['api', 'web']) {
    const file = join(root, 'apps', app, 'package.json');
    const pkg = JSON.parse(readFileSync(file, 'utf8')) as { dependencies: Record<string, string> };
    let dirty = false;
    for (const m of mods) {
      if (pkg.dependencies[m.packageName] !== 'workspace:*') {
        pkg.dependencies[m.packageName] = 'workspace:*';
        dirty = true;
      }
    }
    for (const dep of Object.keys(pkg.dependencies)) {
      if (dep.startsWith('@isbp/module-') && !mods.some((m) => m.packageName === dep)) {
        delete pkg.dependencies[dep];
        dirty = true;
      }
    }
    if (dirty) {
      pkg.dependencies = Object.fromEntries(
        Object.entries(pkg.dependencies).sort(([a], [b]) => a.localeCompare(b)),
      );
      changed.push(file);
      if (write) writeFileSync(file, `${JSON.stringify(pkg, null, 2)}\n`);
    }
  }
  return changed;
}

/** Writes (or, with `check`, compares) the generated registry files. Returns out-of-date paths. */
export function syncRegistries(root: string, check = false): string[] {
  const mods = discoverModules(root);
  const outputs: [string, string][] = [
    [join(root, 'apps/api/src/generated/modules.ts'), renderApiRegistry(mods)],
    [join(root, 'apps/api/src/generated/module-messages.ts'), renderMessagesRegistry(mods)],
    [join(root, 'apps/web/src/generated/modules.ts'), renderWebRegistry(mods)],
    [join(root, 'apps/web/src/generated/module-messages.ts'), renderMessagesRegistry(mods)],
  ];
  const stale: string[] = [];
  for (const [file, content] of outputs) {
    const current = existsSync(file) ? readFileSync(file, 'utf8') : '';
    if (current !== content) {
      stale.push(file);
      if (!check) writeFileSync(file, content);
    }
  }
  stale.push(...syncAppDependencies(root, mods, !check));
  return stale;
}
