#!/usr/bin/env tsx
/**
 * Embeds drizzle-kit SQL migrations into `<dir>/index.ts` so bundles and Docker images carry them
 * without filesystem lookups. Usage: `isbp-embed-migrations <migrations-dir> [--check]`.
 */
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const args = process.argv.slice(2);
const check = args.includes('--check');
const dir = resolve(args.find((a) => !a.startsWith('--')) ?? 'migrations');
const journalPath = join(dir, 'meta', '_journal.json');

let entries: { idx: number; tag: string }[] = [];
if (existsSync(journalPath)) {
  entries = (JSON.parse(readFileSync(journalPath, 'utf8')) as { entries: { idx: number; tag: string }[] })
    .entries;
}

const migrations = entries
  .sort((a, b) => a.idx - b.idx)
  .map(({ tag }) => {
    // A Windows checkout has CRLF line endings: hash and embed what git stores (LF), or every applied
    // migration's hash would change.
    const sql = readFileSync(join(dir, `${tag}.sql`), 'utf8').replace(/\r\n/g, '\n');
    if (!sql.trim()) throw new Error(`Migration ${tag}.sql is empty — fill in the custom migration first.`);
    const hash = createHash('sha256').update(sql).digest('hex');
    return { tag, hash, sql };
  });

const body = `// AUTO-GENERATED by isbp-embed-migrations — do not edit. Run \`pnpm db:generate\` instead.
import type { Migration } from '@isbp/sdk/server';

export const migrations: Migration[] = ${JSON.stringify(migrations, null, 2)};

export default migrations;
`;

const out = join(dir, 'index.ts');
if (check) {
  const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (current !== body) {
    console.error(`✗ ${out} is out of date. Run \`pnpm db:generate\`.`);
    process.exit(1);
  }
  console.warn(`✓ ${out} is up to date (${migrations.length} migrations)`);
} else {
  writeFileSync(out, body);
  console.warn(`✓ embedded ${migrations.length} migration(s) into ${out}`);
}
