// Publishes the IBM Plex Sans TC and JP weights the UI uses (regular, medium, semibold) under
// public/fonts/<family>-<version>/, with a stylesheet each that the root layout links for zh-TW and ja-JP only. The
// fonts are split by unicode-range, so a browser downloads just the slices a page needs. Generated, not committed:
// `dev` and `build` run this first.
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const out = new URL('../public/fonts/', import.meta.url).pathname;
const WEIGHTS = ['Regular', 'Medium', 'SemiBold'];
const FAMILIES = [
  { pkg: '@ibm/plex-sans-tc', file: 'IBMPlexSansTC', name: 'plex-sans-tc' },
  { pkg: '@ibm/plex-sans-jp', file: 'IBMPlexSansJP', name: 'plex-sans-jp' },
];

mkdirSync(out, { recursive: true });

for (const f of FAMILIES) {
  const root = dirname(require.resolve(`${f.pkg}/package.json`));
  const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
  // The version is in the path, so everything under /fonts is cached as immutable (next.config.ts).
  const dir = `${f.name}-${version}`;
  const stylesheet = join(out, dir, `${f.name}.css`);
  if (existsSync(stylesheet)) continue;

  for (const old of readdirSync(out))
    if (old.startsWith(`${f.name}-`)) rmSync(join(out, old), { recursive: true, force: true });
  mkdirSync(join(out, dir));

  const split = join(root, 'fonts/split/woff2/hinted');
  const rules = [];
  for (const weight of WEIGHTS) {
    const css = readFileSync(join(split, `${f.file}-${weight}.css`), 'utf8');
    rules.push(
      css
        .replace(/url\("([^"]+\.woff2)"\)/g, (_, file) => {
          copyFileSync(join(split, file), join(out, dir, file));
          return `url("/fonts/${dir}/${file}")`;
        })
        // Text shows at once in a fallback font while a slice loads.
        .replace(/(font-weight:[^;]+;)/g, '$1\n\tfont-display: swap;'),
    );
  }
  writeFileSync(
    stylesheet,
    `/* Generated by apps/web/scripts/fonts.mjs from ${f.pkg}@${version}. */\n${rules.join('\n')}`,
  );
  process.stdout.write(`fonts: ${f.pkg}@${version} → public/fonts/${dir}/\n`);
}
